// Discovery of the dictionary folders (`src/lib/i18n/<locale>/common.json`), used by the
// generator script and by the parity test: the bundled app cannot read that folder, so the list
// is generated into locales.ts and a test fails when it is stale. English is always present and
// always first (the wizard offers it as the first choice); the others follow alphabetically.
import { existsSync, readdirSync } from "node:fs";
import { join } from "node:path";

export const I18N_DIR = "src/lib/i18n";
export const LOCALES_FILE = join(I18N_DIR, "locales.ts");

export function discoverLocales(dir = I18N_DIR): string[] {
	const found = readdirSync(dir, { withFileTypes: true })
		.filter((e) => e.isDirectory() && /^[a-z]{2}(-[A-Z]{2})?$/.test(e.name))
		.filter((e) => existsSync(join(dir, e.name, "common.json")))
		.map((e) => e.name)
		.sort();
	if (!found.includes("en")) {
		throw new Error(`${dir}: the English dictionaries (en/) must always exist`);
	}
	return ["en", ...found.filter((l) => l !== "en")];
}

export function localesModule(locales: readonly string[]): string {
	return [
		"// SPDX-License-Identifier: GPL-3.0-or-later",
		"// Generated by scripts/generate-locales.ts from the folders of src/lib/i18n — do not edit.",
		"// Run `bun run i18n:locales` after adding or removing a language folder.",
		`export const LOCALES = [${locales.map((l) => JSON.stringify(l)).join(", ")}] as const;`,
		"",
	].join("\n");
}
