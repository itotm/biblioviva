// The format table (PLAN.md Phase 12, step 12.1): every format the library's codes can have, per
// kind — the one generated today, the ones generated in the past (retired) and the legacy shapes
// imported from older systems. It is plain data (it travels to the browser with the layout data)
// and is compiled once by `buildCodeTable`; recognition (scan.ts) and the rule that copies and
// cards can never be confused (compare.ts) both read it.
import type { KeyboardLayout } from "./layouts.js";
import { compileFormat, generateCode, type CompiledFormat, type FormatDef } from "./pattern.js";

export type CodeKind = "item" | "card";
export const CODE_KINDS: readonly CodeKind[] = ["item", "card"];

export interface KindFormats {
	/** The format new codes get. */
	current: FormatDef;
	/** Formats generated by the app in the past: recognised and validated, never generated. */
	retired: FormatDef[];
	/** Shapes of codes imported from older systems (no counter needed, usually no check). */
	legacy: FormatDef[];
}

export interface CodeFormats {
	item: KindFormats;
	card: KindFormats;
	/**
	 * Plain numbers of older systems (cards or copies, no way to tell) have up to this many digits;
	 * any all-digit text that matches no format is looked up in both tables. 0 = none exist.
	 */
	plainMaxLength: number;
	/** `barcodes.libraryCode` for the `{lib}` token. */
	libraryCode: string;
	/** Keyboard layout of the computers the scanners type into (repair tables). */
	layout: KeyboardLayout;
	/**
	 * Card numbers in the generated format whose counter is below this value may be legacy numbers
	 * of the same shape: their check is not verified (the formats of 2026, PLAN.md §3.7).
	 */
	cardCounterStart?: number;
}

export interface CompiledKind {
	current: CompiledFormat;
	retired: CompiledFormat[];
	legacy: CompiledFormat[];
}

export interface CodeTable {
	formats: CodeFormats;
	item: CompiledKind;
	card: CompiledKind;
}

function compileKind(kind: KindFormats, libraryCode: string): CompiledKind {
	return {
		current: compileFormat(kind.current, { libraryCode }),
		retired: kind.retired.map((f) => compileFormat(f, { libraryCode })),
		legacy: kind.legacy.map((f) => compileFormat(f, { libraryCode, counterOptional: true })),
	};
}

/** Compiles the table; throws `PatternError` on an invalid pattern (the configuration validates first). */
export function buildCodeTable(formats: CodeFormats): CodeTable {
	return {
		formats,
		item: compileKind(formats.item, formats.libraryCode),
		card: compileKind(formats.card, formats.libraryCode),
	};
}

/** An example of each kind's current format (for messages that say what a code looks like). */
export function codeExamples(table: CodeTable, year: number): { item: string; card: string } {
	return {
		item: generateCode(table.item.current, { counter: 123, year }),
		card: generateCode(table.card.current, { counter: 123, year }),
	};
}
